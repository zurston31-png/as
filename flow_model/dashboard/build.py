def audit_no_local_statistics(source: str | None = None) -> tuple[str, ...]:
    """Every arithmetic operation, aggregator call and numeric import here.

    Returns an empty tuple for this module, which is the point: the guarantee
    that no statistic is computed in the dashboard is a property of the parse
    tree, not a promise in a docstring. Matched on the AST rather than on the
    text, so prose describing the rule cannot trip it and a `/` inside a
    string cannot hide from it.

    `BitOr` is not forbidden: `MetricValue | None` is a type union.
    """
    text = source if source is not None else Path(__file__).read_text(encoding="utf-8")
    offenders: list[str] = []
    for node in ast.walk(ast.parse(text)):
        if isinstance(node, ast.BinOp) and isinstance(node.op, FORBIDDEN_BINOPS):
            offenders.append(
                f"line {node.lineno}: arithmetic {type(node.op).__name__}"
            )
        elif isinstance(node, ast.AugAssign) and isinstance(node.op, FORBIDDEN_BINOPS):
            offenders.append(
                f"line {node.lineno}: augmented arithmetic {type(node.op).__name__}"
            )
        elif isinstance(node, ast.Call):
            name = (
                node.func.id
                if isinstance(node.func, ast.Name)
                else node.func.attr if isinstance(node.func, ast.Attribute) else ""
            )
            if name in FORBIDDEN_CALLS:
                offenders.append(f"line {node.lineno}: call to {name}()")
        elif isinstance(node, ast.Import):
            for alias in node.names:
                if alias.name.split(".")[0] in FORBIDDEN_IMPORTS:
                    offenders.append(f"line {node.lineno}: import {alias.name}")
        elif isinstance(node, ast.ImportFrom):
            root = (node.module or "").split(".")[0]
            if root in FORBIDDEN_IMPORTS:
                offenders.append(f"line {node.lineno}: from {node.module} import ...")
    return tuple(offenders)


