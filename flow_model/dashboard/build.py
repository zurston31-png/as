class Panel(FrozenModel):
    """One panel: a body, or an explicit reason there is none. Never both.

    `provenance` is required and may not be blank, so a panel cannot exist
    without stating what produced it -- the rule that a chart must not be
    separable from its source, enforced at construction rather than reviewed.
    """

    panel_id: PanelId
    title: str
    provenance: str
    body: str = ""
    undefined: Undefined | None = None
    n: int = Field(ge=0, default=0)
    note: str = ""

    @property
    def is_defined(self) -> bool:
        return self.undefined is None

    @model_validator(mode="after")
    def _check(self) -> "Panel":
        has_body = bool(self.body)
        has_reason = self.undefined is not None
        if has_body == has_reason:
            raise ValueError(
                f"panel {self.panel_id.value} carries "
                f"{'both a body and an undefined reason' if has_body else 'neither'}; "
                "a panel states a measurement or states that there is none, exactly "
                "as a MetricValue does"
            )
        if not self.provenance.strip():
            raise ValueError(
                f"panel {self.panel_id.value} has no provenance label. A chart "
                "whose data source is not stated on it can be screenshotted into "
                "something it is not"
            )
        return self


def _undefined_panel(
    panel_id: PanelId, reason: Undefined, *, provenance: str, n: int = 0, note: str = ""
) -> Panel:
    return Panel(
        panel_id=panel_id,
        title=PANEL_TITLES[panel_id],
        provenance=provenance,
        undefined=reason,
        n=n,
        note=note,
    )


