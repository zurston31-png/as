class DashboardPage(FrozenModel):
    """The eleven panels, the origin notice, and the run's own provenance."""

    notice: OriginNotice
    panels: tuple[Panel, ...]
    run_id: str
    symbol: str
    facts: tuple[tuple[str, str], ...]
    funnel: tuple[tuple[str, str], ...]

    def panel(self, panel_id: PanelId) -> Panel:
        for candidate in self.panels:
            if candidate.panel_id is panel_id:
                return candidate
        raise KeyError(f"no {panel_id.value} panel")

    @property
    def n_undefined(self) -> int:
        return len([p for p in self.panels if not p.is_defined])

    @model_validator(mode="after")
    def _check(self) -> "DashboardPage":
        present = tuple(panel.panel_id for panel in self.panels)
        if present != tuple(PanelId):
            raise ValueError(
                f"the page holds {[p.value for p in present]} but section 12 names "
                f"{[p.value for p in PanelId]}, in that order. A page that can drop "
                "a panel can drop the one that looked bad"
            )
        return self


def _facts(provenance: RunProvenance, run: RunResult) -> tuple[tuple[str, str], ...]:
    """Run identity, as strings. No clock is read: the timestamp is the run's."""
    stamp = (
        provenance.created_at.isoformat()
        if provenance.created_at is not None
        else "not recorded by the run (no clock is read at render time)"
    )
    return (
        ("run_id", provenance.run_id),
        ("symbol", provenance.symbol),
        ("split_label", str(provenance.split_label)),
        ("split_name", provenance.split_name if provenance.split_name else "unnamed"),
        ("config_hash", provenance.config_hash),
        ("data_hash", provenance.data_hash),
        ("inputs_fingerprint", provenance.inputs_fingerprint()),
        ("result_fingerprint", run.result_fingerprint()),
        ("seed", f"{provenance.seed}"),
        ("git_commit", provenance.git_commit if provenance.git_commit else "unrecorded"),
        ("git_dirty", f"{provenance.git_dirty}"),
        ("code_version", provenance.code_version),
        ("run timestamp (from the run, not the clock)", stamp),
        ("bars in clock", f"{provenance.bars_in_clock}"),
        ("bars processed", f"{provenance.bars_processed}"),
        ("clock truncated", f"{provenance.clock_truncated}"),
        ("bars evaluated", f"{run.bars_evaluated}"),
        ("first bar", str(provenance.first_ts)),
        ("last bar", str(provenance.last_ts)),
        ("interval seconds", f"{provenance.interval_seconds}"),
        ("starting equity (USD)", f"{provenance.starting_equity:{VALUE_FORMAT}}"),
        ("compound equity", f"{provenance.compound_equity}"),
        ("trades", f"{run.trade_count}"),
        ("open at end", f"{run.open_at_end}"),
        ("unresolved orders", f"{run.unresolved_orders}"),
        ("submissions declined", f"{run.submissions_declined}"),
        ("dataset", "; ".join(f"{k}={v}" for k, v in sorted(provenance.dataset.items()))),
    )


def _funnel(run: RunResult) -> tuple[tuple[str, str], ...]:
    """Where the trades went, in counts. The first thing to read on an empty run."""
    rows: list[tuple[str, str]] = []
    for key in ("bars_evaluated", "signal_rows_kept", "waits_dropped_by_config",
                "orders_submitted"):
        if key in run.rejection:
            rows.append((key, f"{run.rejection[key]}"))
    for key in ("actions", "wait_reasons", "blocking_stages", "order_outcomes",
                "exit_reasons"):
        histogram = run.rejection.get(key)
        if isinstance(histogram, Mapping):
            rendered = ", ".join(f"{k}={v}" for k, v in sorted(
                histogram.items(), key=lambda item: str(item[0])
            ))
            rows.append((key, rendered if rendered else "none"))
    terminal = run.rejection.get("terminal_gate")
    if isinstance(terminal, Mapping):
        rows.append((
            "terminal gate",
            f"{terminal.get('reason')} blocked {terminal.get('count')} bar(s)",
        ))
    for key in sorted(run.limit_trips):
        rows.append((f"risk limit trip: {key}", f"{run.limit_trips[key]}"))
    return tuple(rows)


def build_page(inputs: DashboardInputs) -> DashboardPage:
    """Assemble the eleven panels. Computes nothing; reads `inputs`."""
    notice = origin_notice(inputs.provenance.dataset)
    return DashboardPage(
        notice=notice,
        panels=tuple(builder(inputs, notice) for builder in PANEL_BUILDERS),
        run_id=inputs.provenance.run_id,
        symbol=inputs.provenance.symbol,
        facts=_facts(inputs.provenance, inputs.run),
        funnel=_funnel(inputs.run),
    )


