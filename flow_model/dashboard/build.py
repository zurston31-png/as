def _fmt(value: MetricValue | None) -> str:
    """A `MetricValue` as text. Undefined renders as undefined, with its n."""
    if value is None:
        return "not reported"
    if value.value is None:
        return f"undefined ({value.undefined}) n={value.n}"
    unit = f" {value.unit}" if value.unit else ""
    return f"{value.value:{VALUE_FORMAT}}{unit} (n={value.n})"


def _cell_metric(cells_metrics: Mapping[str, MetricValue], name: str) -> MetricValue:
    """One metric out of a breakdown cell, or an undefined standing in for it.

    A caller that asked for a metric the cell does not carry gets a
    `MetricValue` saying so, rather than a `KeyError` or a zero.
    """
    found = cells_metrics.get(name)
    if found is not None:
        return found
    return MetricValue.undefined_because(name, Undefined.INPUT_NOT_SUPPLIED)


def _table(headers: Sequence[str], rows: Sequence[Sequence[str]]) -> str:
    head = "".join(f"<th>{escape(str(h))}</th>" for h in headers)
    body = "".join(
        f"<tr>{''.join(f'<td>{escape(str(c))}</td>' for c in row)}</tr>" for row in rows
    )
    return f"<table><thead><tr>{head}</tr></thead><tbody>{body}</tbody></table>"


def _figure_html(
    figure: go.Figure,
    *,
    div_id: str,
    notice: OriginNotice,
    x_title: str,
    y_title: str,
) -> str:
    """A figure as a self-contained HTML fragment, deterministically.

    `div_id` is explicit because `to_html` otherwise mints a random uuid,
    which would make two renders of one run differ byte for byte. The origin
    annotation is drawn INSIDE the figure so that an image cropped out of this
    page still carries it.
    """
    figure.update_layout(
        template=PLOTLY_TEMPLATE,
        height=FIGURE_HEIGHT_PX,
        margin={"l": 70, "r": 70, "t": 48, "b": 56},
        xaxis_title=x_title,
        yaxis_title=y_title,
        legend={"orientation": "h", "y": 1.08, "x": 0.0},
    )
    figure.add_annotation(
        text=notice.watermark,
        xref="paper",
        yref="paper",
        x=0.5,
        y=0.5,
        showarrow=False,
        font={"size": WATERMARK_FONT_PX, "color": WATERMARK_COLOUR},
        opacity=WATERMARK_OPACITY,
        align="center",
    )
    return to_html(
        figure,
        include_plotlyjs=False,
        full_html=False,
        div_id=div_id,
        config={"displayModeBar": False, "staticPlot": False},
    )


def _breakdown_figure(
    bd: Breakdown, *, overlay: str, div_id: str, notice: OriginNotice, x_title: str
) -> str:
    """Counts as bars, one analytics metric as an overlay on a second axis.

    Undefined cells leave a GAP in the overlay (`connectgaps=False`) rather
    than being dropped or drawn at zero: a gap says "no number here", a point
    at zero says "we measured zero", and a dropped cell silently filters the
    sample.
    """
    labels = [cell.key for cell in bd.cells]
    counts = [cell.n for cell in bd.cells]
    values = [_cell_metric(cell.metrics, overlay).or_none() for cell in bd.cells]
    unit = _cell_metric(bd.cells[0].metrics, overlay).unit if bd.cells else ""
    figure = go.Figure()
    figure.add_bar(x=labels, y=counts, name="trades (count)", marker_color=COUNT_COLOUR)
    figure.add_scatter(
        x=labels,
        y=values,
        name=f"{overlay} ({unit if unit else 'unitless'})",
        mode="markers+lines",
        connectgaps=False,
        yaxis="y2",
        marker_color=OVERLAY_COLOUR,
    )
    figure.update_layout(
        yaxis2={
            "overlaying": "y",
            "side": "right",
            "title": f"{overlay} ({unit if unit else 'unitless'})",
        }
    )
    return _figure_html(
        figure, div_id=div_id, notice=notice, x_title=x_title, y_title="trades (count)"
    )


def _breakdown_table(bd: Breakdown) -> str:
    headers = ["cell", "n", "wins", "losses", "scratch", "sample", *bd.metric_names]
    rows = [
        [
            cell.key,
            f"{cell.n}",
            f"{cell.n_wins}",
            f"{cell.n_losses}",
            f"{cell.n_scratch}",
            str(cell.status),
            *(_fmt(_cell_metric(cell.metrics, name)) for name in bd.metric_names),
        ]
        for cell in bd.cells
    ]
    return _table(headers, rows)


