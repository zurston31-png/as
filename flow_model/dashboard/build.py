def _panel_trade_distribution(inputs: DashboardInputs, notice: OriginNotice) -> Panel:
    panel_id = PanelId.TRADE_DISTRIBUTION
    dist = inputs.primary.r_distribution
    source = (
        "analytics.r_distribution over TradeRecord.r_multiple "
        "(= pnl / risk_dollars, the planned-R denominator fixed at signal time, "
        f"ARCHITECTURE 0.2); n={dist.n_trades}; {notice.detail}"
    )
    if inputs.run.is_empty:
        return _undefined_panel(
            panel_id, Undefined.NO_TRADES, provenance=source, note=ZERO_TRADE_PANEL_NOTE
        )
    figure = go.Figure()
    figure.add_bar(
        x=[bucket.label for bucket in dist.histogram],
        y=[bucket.count for bucket in dist.histogram],
        name="trades (count)",
        marker_color=COUNT_COLOUR,
    )
    percentiles = ", ".join(
        f"{key} {_fmt(value)}" for key, value in sorted(dist.percentiles.items())
    )
    return Panel(
        panel_id=panel_id,
        title=PANEL_TITLES[panel_id],
        provenance=source,
        body=_figure_html(
            figure, div_id=panel_id.value, notice=notice,
            x_title="realized R bucket", y_title="trades (count)",
        ),
        n=dist.n_trades,
        note=(
            f"mean {_fmt(dist.mean)}; median {_fmt(dist.median)}; "
            f"sd {_fmt(dist.stdev)}; min {_fmt(dist.minimum)}; "
            f"max {_fmt(dist.maximum)}. Percentiles: {percentiles}. A stop that "
            "triggered worse than planned shows as worse than -1R by design; a "
            "distribution with every loss at exactly -1.00R has re-derived R "
            "from the fill."
        ),
    )


def _panel_mc_fan(inputs: DashboardInputs, notice: OriginNotice) -> Panel:
    panel_id = PanelId.MC_PERCENTILE_FAN
    mc = inputs.monte_carlo
    if mc is None:
        return _undefined_panel(
            panel_id, Undefined.INPUT_NOT_SUPPLIED,
            provenance=f"no monte_carlo result supplied; {notice.detail}",
            note=MC_ABSENT_NOTE,
        )
    source = (
        f"monte_carlo result: method={mc.method}, n_simulations={mc.n_simulations}, "
        f"trades resampled={mc.n_trades_resampled}, seed={mc.seed}, "
        f"compound={mc.compound}. {mc.provenance} {notice.detail}"
    )
    if not mc.fan or not mc.steps:
        return _undefined_panel(
            panel_id, Undefined.INPUT_NOT_SUPPLIED, provenance=source,
            n=mc.n_simulations,
            note=(
                "The result carried no percentile curves (n_curves_to_store may be "
                "zero), so there is no fan to draw."
            ),
        )
    figure = go.Figure()
    for band in mc.fan:
        figure.add_scatter(
            x=list(mc.steps),
            y=list(band.equity),
            name=f"p{band.percentile:g}",
            mode="lines",
            line={"color": FAN_COLOUR},
        )
    return Panel(
        panel_id=panel_id,
        title=PANEL_TITLES[panel_id],
        provenance=source,
        body=_figure_html(
            figure, div_id=panel_id.value, notice=notice,
            x_title="trade number within a simulated sequence",
            y_title="simulated equity (USD)",
        ),
        n=mc.n_simulations,
        note=" ".join((
            "Resampling the observed trades cannot produce a regime absent from "
            "the sample: this bounds SEQUENCE risk, not MODEL risk (ARCHITECTURE "
            "11).",
            *mc.notes,
        )),
    )


