class DataOrigin(StrEnum):
    """Whether the run's bars were real, generated, or unaccounted for."""

    SYNTHETIC = "SYNTHETIC"
    UNDECLARED = "UNDECLARED"
    REAL = "REAL"

    @property
    def needs_warning(self) -> bool:
        """True for everything but a positively declared real dataset."""
        return self is not DataOrigin.REAL


class OriginNotice(FrozenModel):
    """The origin, and the exact words used to say so in three places."""

    origin: DataOrigin
    source: str
    headline: str
    watermark: str
    detail: str

    @property
    def needs_warning(self) -> bool:
        return self.origin.needs_warning


def origin_notice(dataset: Mapping[str, object] | None) -> OriginNotice:
    """Read the origin off `RunProvenance.dataset`.

    The default is the warning. `SymbolData.describe()` emits `source` and
    `synthetic` precisely so a synthetic run cannot serialize as
    indistinguishable from a real one, and this reads those two fields -- but
    a dataset that declares nothing is reported `UNDECLARED` and warned about
    just as loudly, because "no marker" and "real bars" are not the same claim
    and only one of them has been checked.
    """
    fields: Mapping[str, object] = dataset if dataset else {}
    raw_source = fields.get("source")
    source = str(raw_source) if raw_source else ""
    declared = fields.get("synthetic")

    if declared:
        return OriginNotice(
            origin=DataOrigin.SYNTHETIC,
            source=source if source else "unnamed synthetic generator",
            headline=(
                "SYNTHETIC DATA. THIS IS NOT A MARKET RESULT. Every bar behind "
                "every panel below was produced by a generator; no real market "
                "bar has ever entered this system. Nothing here is evidence "
                "about markets -- it is evidence about code."
            ),
            watermark="SYNTHETIC DATA -- NOT A MARKET RESULT",
            detail=(
                f"dataset source={source if source else 'unknown'}, "
                "synthetic=True (declared by the dataset itself)"
            ),
        )

    if declared is False and source and source != "unknown":
        return OriginNotice(
            origin=DataOrigin.REAL,
            source=source,
            headline=(
                f"Dataset declares real market bars from {source}. Read the "
                "coverage and exclusion report before treating any panel as "
                "evidence."
            ),
            watermark=f"source: {source}",
            detail=f"dataset source={source}, synthetic=False (declared)",
        )

    return OriginNotice(
        origin=DataOrigin.UNDECLARED,
        source=source,
        headline=(
            "DATA ORIGIN UNDECLARED. The run's dataset did not state whether "
            "its bars are real or generated, so nothing below may be read as "
            "a market result. Every figure this project has published so far "
            "came from a synthetic generator."
        ),
        watermark="ORIGIN UNDECLARED -- NOT EVIDENCE",
        detail=(
            f"dataset source={source if source else 'absent'}, "
            "synthetic marker absent"
        ),
    )


