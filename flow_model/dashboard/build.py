def _panel_equity(inputs: DashboardInputs, notice: OriginNotice) -> Panel:
    panel_id = PanelId.EQUITY_CURVE
    source = (
        f"RunResult.equity ({len(inputs.run.equity)} EquityPoint rows) of run "
        f"{inputs.provenance.run_id}; {notice.detail}"
    )
    if inputs.run.is_empty:
        return _undefined_panel(
            panel_id, Undefined.NO_TRADES, provenance=source, note=ZERO_TRADE_PANEL_NOTE
        )
    if not inputs.run.equity:
        return _undefined_panel(
            panel_id, Undefined.NO_EQUITY_SERIES, provenance=source,
            note="The run recorded no equity rows, which is absence of data.",
        )
    figure = go.Figure()
    figure.add_scatter(
        x=[point.ts for point in inputs.run.equity],
        y=[point.equity for point in inputs.run.equity],
        name="equity (mark-to-market)",
        mode="lines",
        line={"color": SERIES_COLOUR},
    )
    figure.add_scatter(
        x=[point.ts for point in inputs.run.equity],
        y=[point.high_water_mark for point in inputs.run.equity],
        name="high-water mark",
        mode="lines",
        line={"color": OVERLAY_COLOUR, "dash": "dot"},
    )
    return Panel(
        panel_id=panel_id,
        title=PANEL_TITLES[panel_id],
        provenance=source,
        body=_figure_html(
            figure, div_id=panel_id.value, notice=notice,
            x_title="bar close (UTC)", y_title="equity (USD)",
        ),
        n=len(inputs.run.equity),
        note=(
            "EquityPoint.equity and .high_water_mark are stored fields, plotted "
            f"as stored. Total return: {_fmt(inputs.primary.total_return)}. "
            f"CAGR: {_fmt(inputs.primary.cagr)}."
        ),
    )


