def _panel_flow_score(inputs: DashboardInputs, notice: OriginNotice) -> Panel:
    panel_id = PanelId.FLOW_SCORE_DISTRIBUTION
    bd = inputs.flow_score
    source = (
        f"analytics.breakdown over the '{bd.dimension}' dimension "
        f"({bd.description}); win rate is analytics.win_rate per cell, suppressed "
        f"below min_sample_n={bd.min_sample_n}; {notice.detail}"
    )
    if inputs.run.is_empty:
        return _undefined_panel(
            panel_id, Undefined.NO_TRADES, provenance=source, note=ZERO_TRADE_PANEL_NOTE
        )
    return Panel(
        panel_id=panel_id,
        title=PANEL_TITLES[panel_id],
        provenance=source,
        body="".join((
            _breakdown_figure(
                bd, overlay="win_rate", div_id=panel_id.value, notice=notice,
                x_title="Flow Score bucket at entry",
            ),
            _breakdown_table(bd),
        )),
        n=bd.n_trades,
        note=(
            f"{bd.n_insufficient} cell(s) below min_sample_n and {bd.n_empty} empty; "
            "their win rate is undefined and leaves a gap in the overlay. A win "
            "rate over a handful of trades is the primary way people fool "
            "themselves, so it is not drawn at all."
        ),
    )


