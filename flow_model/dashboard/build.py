"""Static Plotly dashboard: section 12's eleven panels, rendered honestly.

A dashboard is the most dangerous artifact this repository produces, because a
chart reads as evidence in a way a number in a log never does. A reader
skims a rising equity curve and remembers "it works"; they do not remember
that the bars were generated by `data/synthetic.py`. So this module is built
around four refusals rather than around plotting.

## 1. No statistic is computed here

Every number on the page arrives as a `MetricValue` from `analytics/`, as a
field of a `TradeRecord` / `EquityPoint` / `RunProvenance`, or as a count of
rows. A dashboard that computes its own win rate can disagree with the report
and there is then no way to tell which is wrong.

This is structural rather than promised: **this module's own source contains
no arithmetic operator and imports no numerical library.** No `+`, `-`, `*`,
`/`, `//`, `%` or `**`; no `sum`, `max`, `min`, `abs`, `round`; no `numpy`, no
`math`, no `statistics`. `audit_no_local_statistics()` walks this file's AST
and returns every violation, so the guarantee is checkable by machine rather
than by reading. Two visible consequences:

* rates are printed as the fractions `analytics` produces (`0.541900
  fraction`), never as percentages, because converting one would be a
  multiplication and a 100x slip is exactly the kind of error nobody audits;
* "cumulative P&L" is drawn as `EquityPoint.realized_equity`, the stored
  field, and the panel says in words that cumulative P&L is that series less
  the starting balance. The offset is not applied, because applying it would
  be arithmetic.

Type unions (`X | None`) are `BitOr` and are allowed; they are not arithmetic
on a measurement.

## 2. An empty panel is an explicit "undefined, n=0", never an empty chart

Over the 19542 synthetic NQ 5-minute bars of 2016 at the committed config, no
bar's Flow Score reaches the lowest setup threshold of 70.0 and the system
takes zero trades. (PROVENANCE.md sections 2.4 and 4a hold the figures of
record, including the correction that superseded an earlier claim; they are
not restated here, because a measurement copied into a docstring goes stale
silently.) **The empty run is the live path.** Most panels on a run today
therefore have nothing to draw, and
the forbidden renderings are precisely the plausible ones: an empty chart, a
zero line, or a flat equity curve sitting at the starting balance. Each of
those reads as "we measured, and nothing happened" when the truth is "there is
no measurement here at all".

`Panel` carries either a body or an `Undefined` reason, never both and never
neither, validated at construction -- the same shape as `MetricValue`, and for
the same reason. `Undefined` is imported from `analytics.metrics`; this module
does not define a second representation of absence.

Which panels gate on the trade count is a judgement recorded here: the equity
curve, the drawdown curve, both P&L panels, the Flow Score distribution, the
regime panel and the trade distribution all describe trade outcomes, so with
no trades they are undefined. The walk-forward fold table and the IS/OOS panel
do NOT gate on it: they are tables whose cells carry their own n, and a fold
reporting n=0 is the bad period this project is forbidden to hide.

## 3. The origin of the data is unmissable, and survives a crop

Every number this project has ever produced came from a synthetic generator;
no real market bar has ever entered the system (PROVENANCE.md). A page that
mentions that in a footnote has not said it, because panels get screenshotted
one at a time. So the origin is stated in three places that a crop cannot
separate from the chart: a full-width banner at the top of the page, a ribbon
on every panel card, and an annotation drawn INSIDE every Plotly figure.

`origin_notice()` decides the wording from `RunProvenance.dataset`, and the
default is suspicion: silence earns the warning. Only a dataset that
positively declares `synthetic=False` with a named `source` renders as `REAL`;
a dataset with no marker at all is `UNDECLARED` and gets a warning of its own.
`render()` re-checks its own output and raises if the banner is missing, so
there is no code path that returns warning-free HTML for unverified data.

## 4. Determinism

Same inputs, byte-identical HTML. Plotly's `to_html` invents a random `div id`
when it is not given one, which would make two renders of one run differ, so
every figure is given an explicit id derived from its panel. There is no clock
read anywhere in this module: the rendered page's "run timestamp" is
`RunProvenance.created_at`, and when the run did not record one the page says
so instead of substituting today.

## What this module does NOT do

It does not read `config/defaults.yaml`, select a parameter, or place an order.
It has no network, no database and no scheduler. `write_dashboard` is the only
function that touches the filesystem.
"""

