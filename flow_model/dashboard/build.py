class DailyPnl(FrozenModel):
    """One calendar day's realized P&L, as `analytics.total_pnl` reports it.

    Grouped by EXIT date, not entry date: the money lands when the position
    closes, which is what makes this series line up with the equity curve.
    """

    day: date
    pnl: MetricValue
    n_trades: int = Field(ge=0)


class McFanBand(FrozenModel):
    """One percentile curve of the Monte Carlo equity fan.

    The values are the engine's own percentile curves. They are floats rather
    than `MetricValue`s because a band is present or absent as a whole: a
    percentile curve with a missing point is a bug in the engine, not an
    undefined measurement, and `_check` refuses it here.
    """

    percentile: float = Field(gt=0.0, lt=100.0)
    equity: tuple[float, ...]


class MonteCarloPanelData(FrozenModel):
    """What the two Monte Carlo panels read.

    PROVISIONAL. `monte_carlo/engine.py` is Phase 9 and does not exist at this
    commit, so there is no result object to accept. This is the input contract
    the two panels need, holding `MetricValue`s so that an undefined percentile
    stays undefined; when the engine lands, its caller fills this (or this type
    is replaced by the engine's own result and the panels read that instead).
    No Monte Carlo arithmetic happens here or anywhere in this module.
    """

    method: str
    n_simulations: int = Field(ge=0)
    n_trades_resampled: int = Field(ge=0)
    seed: int
    compound: bool = True
    provenance: str = ""
    steps: tuple[int, ...] = ()
    fan: tuple[McFanBand, ...] = ()
    terminal_percentiles: dict[str, MetricValue] = Field(default_factory=dict)
    notes: tuple[str, ...] = ()

    @model_validator(mode="after")
    def _check(self) -> "MonteCarloPanelData":
        for band in self.fan:
            if len(band.equity) != len(self.steps):
                raise ValueError(
                    f"fan band p{band.percentile:g} has {len(band.equity)} points "
                    f"against {len(self.steps)} steps; a percentile curve with a "
                    "hole in it would plot as a measurement it is not"
                )
        return self


class DashboardInputs(FrozenModel):
    """Everything the page draws, already computed by `analytics`/`validation`.

    Built by `collect()`. Holding this separately from the rendering is what
    makes the no-statistics rule enforceable: by the time a panel function
    runs, there is nothing left to compute.
    """

    run: RunResult
    summaries: tuple[PerformanceSummary, ...]
    flow_score: Breakdown
    regime: Breakdown
    daily_pnl: tuple[DailyPnl, ...] = ()
    monte_carlo: MonteCarloPanelData | None = None
    walk_forward: WalkForwardReport | None = None

    @property
    def provenance(self) -> RunProvenance:
        return self.run.provenance

    @property
    def primary(self) -> PerformanceSummary:
        return self.summaries[0]

    @model_validator(mode="after")
    def _check(self) -> "DashboardInputs":
        if not self.summaries:
            raise ValueError(
                "a dashboard needs at least the primary performance summary; "
                "without one there is no MetricValue to render and the page "
                "would have to compute its own"
            )
        labels = [summary.split_label for summary in self.summaries]
        if len(set(labels)) != len(labels):
            raise ValueError(
                f"two summaries carry the same split label: {labels}. Section 0.8 "
                "forbids an unlabelled aggregate, and two columns under one "
                "label is that aggregate with extra steps"
            )
        if self.primary.split_label is not self.run.provenance.split_label:
            raise ValueError(
                f"the primary summary is labelled {self.primary.split_label} but the "
                f"run is {self.run.provenance.split_label}: a performance number "
                "filed under the wrong phase is an in-sample result reported as OOS"
            )
        if self.primary.n_trades != self.run.trade_count:
            raise ValueError(
                f"the primary summary covers {self.primary.n_trades} trade(s) "
                f"against the run's {self.run.trade_count}"
            )
        return self


def collect(
    run: RunResult,
    *,
    policy: MetricPolicy | None = None,
    monte_carlo: MonteCarloPanelData | None = None,
    walk_forward: WalkForwardReport | None = None,
    extra_summaries: Sequence[PerformanceSummary] = (),
) -> DashboardInputs:
    """Call `analytics` once, for everything the page needs.

    This is the ONLY function in the module that calls an analytics entry
    point, and it does no arithmetic of its own: the grouping below is
    selection, and every sum is `analytics.total_pnl`'s.
    """
    label = run.provenance.split_label
    summary = performance_summary(
        run.trades, run.equity, split_label=label, policy=policy
    )
    by_day: dict[date, list[TradeRecord]] = {}
    for trade in run.trades:
        by_day.setdefault(trade.exit_ts.date(), []).append(trade)
    daily = tuple(
        DailyPnl(
            day=day,
            pnl=total_pnl(by_day[day], split_label=label, policy=policy),
            n_trades=len(by_day[day]),
        )
        for day in sorted(by_day)
    )
    return DashboardInputs(
        run=run,
        summaries=(summary, *extra_summaries),
        flow_score=breakdown(
            run.trades,
            dimension_by_name("flow_score_bucket", policy=policy),
            split_label=label,
            policy=policy,
            metrics=CELL_METRICS,
        ),
        regime=breakdown(
            run.trades,
            dimension_by_name("regime", policy=policy),
            split_label=label,
            policy=policy,
            metrics=CELL_METRICS,
        ),
        daily_pnl=daily,
        monte_carlo=monte_carlo,
        walk_forward=walk_forward,
    )


