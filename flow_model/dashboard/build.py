def _undefined_block(panel: Panel) -> str:
    parts = [
        '<div class="undef">',
        f'<div class="big">undefined, n={panel.n}</div>',
        f'<div class="why">reason: {escape(str(panel.undefined))}</div>',
    ]
    if panel.note:
        parts.append(f'<div class="why">{escape(panel.note)}</div>')
    parts.append("</div>")
    return "".join(parts)


def _panel_html(panel: Panel, notice: OriginNotice) -> str:
    ribbon_class = "ribbon real" if not notice.needs_warning else "ribbon"
    inner = _undefined_block(panel) if not panel.is_defined else panel.body
    tail = (
        f'<p class="note">{escape(panel.note)}</p>'
        if panel.note and panel.is_defined
        else ""
    )
    return "".join((
        '<section class="card">',
        f'<div class="{ribbon_class}">{escape(notice.watermark)}</div>',
        '<div class="card-body">',
        f"<h2>{escape(panel.title)}</h2>",
        f'<p class="sub">panel id: {escape(panel.panel_id.value)} &middot; n={panel.n}</p>',
        f'<div class="prov">data source: {escape(panel.provenance)}</div>',
        inner,
        tail,
        "</div></section>",
    ))


def assert_origin_is_stated(document: str, page: DashboardPage) -> None:
    """Refuse a rendered document that does not say where its numbers came from.

    Called by `render` on its own output, so there is no code path returning
    warning-free HTML for data whose origin is not verified. It checks the
    TEMPLATE rather than a constant it shares with the emitter: the banner
    element must be there, and there must be at least one origin ribbon per
    panel, because the ribbon is what survives a reader cropping one card out
    of the page. A page whose data origin is REAL needs neither and returns
    early.
    """
    if not page.notice.needs_warning:
        return
    if BANNER_MARKER not in document:
        raise DashboardError(
            f"the rendered page for {page.run_id} has no origin banner while its "
            f"data origin is {page.notice.origin.value}. A page that does not say "
            "where its numbers came from will be read as a market result"
        )
    if document.count(RIBBON_CLASS) < len(page.panels):
        raise DashboardError(
            f"the rendered page for {page.run_id} carries "
            f"{document.count(RIBBON_CLASS)} origin ribbon(s) for "
            f"{len(page.panels)} panel(s) while its data origin is "
            f"{page.notice.origin.value}. A panel without one can be screenshotted "
            "into something it is not"
        )


def render(page: DashboardPage, *, inline_plotlyjs: bool = True) -> str:
    """The whole page as one HTML string.

    Self-contained by default: `plotly.js` is inlined, so the file opens with
    no network. `inline_plotlyjs=False` is for tests and for pages assembled
    into a document that already carries the library.

    The last thing this function does is re-read its own output and refuse to
    return it if the origin banner is missing. That is why there is no code
    path producing warning-free HTML for data whose origin is not verified.
    """
    banner_class = "banner real" if not page.notice.needs_warning else "banner"
    library = (
        f"<script>{get_plotlyjs()}</script>"
        if inline_plotlyjs
        else "<!-- plotly.js not inlined: pass inline_plotlyjs=True -->"
    )
    body = "".join(_panel_html(panel, page.notice) for panel in page.panels)
    document = "".join((
        "<!DOCTYPE html>",
        '<html lang="en"><head><meta charset="utf-8">',
        '<meta name="viewport" content="width=device-width,initial-scale=1">',
        f"<title>Flow Model run {escape(page.run_id)} ({escape(page.symbol)})</title>",
        f"<style>{_STYLE}</style>",
        library,
        "</head><body>",
        f'<div class="{banner_class}" id="{BANNER_MARKER}">',
        escape(page.notice.headline),
        f'<div class="detail">{escape(page.notice.detail)}</div>',
        "</div>",
        '<div class="wrap">',
        f"<h1>Flow Model run {escape(page.run_id)} &middot; {escape(page.symbol)}</h1>",
        f'<p class="sub">{page.n_undefined} of {len(page.panels)} panels are '
        "undefined. Undefined is a state this page renders explicitly; it is "
        "never drawn as a zero.</p>",
        '<section class="card">',
        f'<div class="{"ribbon real" if not page.notice.needs_warning else "ribbon"}">'
        f"{escape(page.notice.watermark)}</div>",
        '<div class="card-body"><h2>Run provenance</h2>',
        '<p class="sub">Every field a third party needs to reproduce this run.</p>',
        _table(["field", "value"], [[k, v] for k, v in page.facts]).replace(
            "<table>", '<table class="kv">'
        ),
        "</div></section>",
        '<section class="card">',
        f'<div class="{"ribbon real" if not page.notice.needs_warning else "ribbon"}">'
        f"{escape(page.notice.watermark)}</div>",
        '<div class="card-body"><h2>Where the trades went</h2>',
        '<p class="sub">Counts from RunResult.rejection, which are defined at '
        "any n. On a run with no trades this is the first thing to read.</p>",
        _table(["stage", "count"], [[k, v] for k, v in page.funnel]).replace(
            "<table>", '<table class="kv">'
        ),
        "</div></section>",
        body,
        "</div></body></html>",
    ))
    assert_origin_is_stated(document, page)
    return document


def build_html(
    run: RunResult,
    *,
    policy: MetricPolicy | None = None,
    monte_carlo: MonteCarloPanelData | None = None,
    walk_forward: WalkForwardReport | None = None,
    extra_summaries: Sequence[PerformanceSummary] = (),
    inline_plotlyjs: bool = True,
) -> str:
    """`RunResult` to HTML, in one call. Deterministic for identical inputs."""
    return render(
        build_page(
            collect(
                run,
                policy=policy,
                monte_carlo=monte_carlo,
                walk_forward=walk_forward,
                extra_summaries=extra_summaries,
            )
        ),
        inline_plotlyjs=inline_plotlyjs,
    )


def write_dashboard(html: str, path: str | Path) -> Path:
    """Write a rendered page. The only filesystem access in this module."""
    target = Path(path)
    if target.parent:
        target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(html, encoding="utf-8")
    return target


