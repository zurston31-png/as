def _panel_walk_forward(inputs: DashboardInputs, notice: OriginNotice) -> Panel:
    panel_id = PanelId.WALK_FORWARD_FOLDS
    report = inputs.walk_forward
    if report is None:
        return _undefined_panel(
            panel_id, Undefined.INPUT_NOT_SUPPLIED,
            provenance=f"no walk-forward report supplied; {notice.detail}",
            note="validation.walk_forward.evaluate_folds produces this report.",
        )
    if not report.folds:
        return _undefined_panel(
            panel_id, Undefined.INPUT_NOT_SUPPLIED,
            provenance=f"walk-forward report with no folds; {notice.detail}",
        )
    headers = ["fold", "phase", "window", "n", "sample", *FOLD_METRICS]
    rows: list[list[str]] = []
    for result in report.folds:
        for window in result.windows:
            rows.append([
                f"{window.fold_index:03d}",
                window.phase.value,
                f"{window.range}",
                f"{window.n_trades}",
                str(window.sample),
                *(
                    _fmt(_cell_metric(window.performance.trade_metrics, name))
                    for name in FOLD_METRICS
                ),
            ])
    return Panel(
        panel_id=panel_id,
        title=PANEL_TITLES[panel_id],
        provenance=(
            f"validation.walk_forward.WalkForwardReport: {report.n_folds} fold(s), "
            f"mode={report.fold_set.spec.mode}, config_hash={report.config_hash}, "
            f"data_hash={report.data_hash}; {notice.detail}"
        ),
        body=_table(headers, rows),
        n=report.n_folds,
        note=(
            "Every fold is listed, empty ones included, and there is no 'best "
            "fold' column: naming one would be selection on the evaluation data. "
            "Cross-fold means are available only through CrossFoldStatement, "
            "which cannot be held without its per-fold vector."
        ),
    )


def _phase_role(phase: SplitPhase | None) -> str:
    if phase is None:
        return "UNLABELLED"
    if phase is SplitPhase.TRAIN:
        return "in-sample (fitting)"
    if phase is SplitPhase.VALIDATION:
        return "in-sample (selection)"
    if phase is SplitPhase.TEST:
        return "out-of-sample"
    return "out-of-sample (sealed)"


def _panel_is_vs_oos(inputs: DashboardInputs, notice: OriginNotice) -> Panel:
    panel_id = PanelId.IS_VS_OOS
    summaries = inputs.summaries
    source = (
        "analytics.performance_summary, one per split phase, never combined "
        f"(ARCHITECTURE 0.8); phases present: "
        f"{', '.join(str(s.split_label) for s in summaries)}; {notice.detail}"
    )
    if len(summaries) < 2:
        return _undefined_panel(
            panel_id, Undefined.INPUT_NOT_SUPPLIED, provenance=source,
            n=len(summaries),
            note=(
                "Only one split phase was supplied, so there is no comparison to "
                "draw. Pass the other phase's PerformanceSummary to collect() as "
                "extra_summaries. Analytics refuses to merge phases, so a single "
                "column is the honest rendering of a single phase."
            ),
        )
    headers = ["metric", *(str(s.split_label) for s in summaries)]
    rows: list[list[str]] = [
        ["role", *(_phase_role(s.split_label) for s in summaries)],
        ["sample", *(str(s.sample) for s in summaries)],
    ]
    for name in IS_OOS_METRICS:
        rows.append([
            name,
            *(_fmt(_cell_metric(s.trade_metrics, name)) for s in summaries),
        ])
    rows.append(["sharpe (annualized)", *(_fmt(s.sharpe) for s in summaries)])
    rows.append(["sortino (annualized)", *(_fmt(s.sortino) for s in summaries)])
    rows.append(["total_return", *(_fmt(s.total_return) for s in summaries)])
    rows.append(["cagr", *(_fmt(s.cagr) for s in summaries)])
    rows.append([
        "max_drawdown_pct",
        *(_fmt(s.drawdown.max_drawdown_pct) for s in summaries),
    ])
    return Panel(
        panel_id=panel_id,
        title=PANEL_TITLES[panel_id],
        provenance=source,
        body=_table(headers, rows),
        n=len(summaries),
        note=(
            "One column per phase and no combined column: section 0.8 refuses to "
            "aggregate in-sample and out-of-sample into one unlabelled number, "
            "and the refusal is in analytics, not here."
        ),
    )


